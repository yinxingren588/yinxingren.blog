/**
 * 根据文章 ID 获取指定文章
 */
export function getHelpArticleById(id: string): HelpArticle | undefined {
  return HELP_ARTICLES.find((a) => a.id === id);
}

/**
 * 获取同类推荐文章（排除当前文章）
 */
export function getRelatedHelpArticles(currentArticle: HelpArticle, limit = 3): HelpArticle[] {
  // 优先同分类，不足时补充其他文章
  const sameCategory = HELP_ARTICLES.filter(
    (a) => a.id !== currentArticle.id && a.category === currentArticle.category
  );
  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }
  const others = HELP_ARTICLES.filter(
    (a) => a.id !== currentArticle.id && a.category !== currentArticle.category
  );
  return [...sameCategory, ...others].slice(0, limit);
}
